"""Draws the yeti rig (scripts/demo/yeti/, cut from site/logo.png by demo/yeti-rig.py) as vector
shapes for the Claude Code plugin's panel: plugins/coolftp/hooks/yeti-art.ts.

Vector, not embedded PNGs: Claude's panel strips <image> from the SVG it draws. Each layer is
traced with vtracer (pip install vtracer) and keeps its place on the 538x594 logo.
Run: python scripts/plugin-yeti.py
"""
import os
import re
import tempfile

import vtracer
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RIG = os.path.join(ROOT, "scripts", "demo", "yeti")
OUT = os.path.join(ROOT, "plugins", "coolftp", "hooks", "yeti-art.ts")

# Each layer and where it sits on the logo.
LAYERS = {"base": (0, 0), "brow": (186, 235), "teeth": (182, 284), "eyeL": (172, 204), "eyeR": (303, 204)}


def hard_edges(src: str, dst: str) -> None:
    """Soft, half-transparent edge pixels trace as a pale rim around each shape: make every
    pixel either solid or gone."""
    img = Image.open(src).convert("RGBA")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            px[x, y] = (r, g, b, 255) if a >= 160 else (0, 0, 0, 0)
    img.save(dst)


def trace(name: str) -> tuple[str, int, int]:
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, name + ".svg")
        src = os.path.join(tmp, name + ".png")
        hard_edges(os.path.join(RIG, name + ".png"), src)
        vtracer.convert_image_to_svg_py(
            src,
            out,
            colormode="color",
            hierarchical="stacked",
            mode="spline",
            filter_speckle=4,
            color_precision=6,
            layer_difference=16,
            corner_threshold=60,
            length_threshold=4.0,
            max_iterations=10,
            splice_threshold=45,
            path_precision=2,
        )
        svg = open(out, encoding="utf-8").read()
    w, h = (int(v) for v in re.search(r'width="(\d+)" height="(\d+)"', svg).groups())
    found = re.findall(r"<path[^>]*/>", svg)
    if name == "base" and len(found) > 2:
        # Stacked tracing fills the whole silhouette twice, white fur then grey shading, out to the
        # logo's soft rim, and the black outline lands just inside it: a pale hairline around him.
        # The silhouette again as a black edge, over both fur layers, covers it.
        edge = re.sub(r'fill="[^"]*"', 'fill="none" stroke="#000000" stroke-width="18" stroke-linejoin="round"', found[0], count=1)
        found.insert(2, edge)
    paths = "".join(found)
    return re.sub(r"\s+", " ", paths).replace("'", "&apos;"), w, h


lines = [
    "// Generated by scripts/plugin-yeti.py from the yeti rig. Do not edit by hand.",
    "/** One layer of the yeti: where it sits on the 538x594 logo, its size there, and its shapes. */",
    "export type YetiLayer = { x: number; y: number; w: number; h: number; svg: string }",
    "",
    "export const YETI: Record<'base' | 'brow' | 'teeth' | 'eyeL' | 'eyeR', YetiLayer> = {",
]
total = 0
for name, (x, y) in LAYERS.items():
    svg, w, h = trace(name)
    total += len(svg)
    lines.append(f"  {name}: {{ x: {x}, y: {y}, w: {w}, h: {h}, svg: '{svg}' }},")
lines.append("}")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {OUT}: {total} characters of shapes")
