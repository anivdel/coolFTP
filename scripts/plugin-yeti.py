"""Embeds the yeti rig (scripts/demo/yeti/, cut from site/logo.png by demo/yeti-rig.py) in the
Claude Code plugin's panel as small PNG data URIs: plugins/coolftp/hooks/yeti-art.ts.

The panel draws the layers in logo pixel coordinates (538x594), so the scale here only sets
how crisp he is. Run: python scripts/plugin-yeti.py
"""
import base64
import io
import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RIG = os.path.join(ROOT, "scripts", "demo", "yeti")
OUT = os.path.join(ROOT, "plugins", "coolftp", "hooks", "yeti-art.ts")
SCALE = 0.4  # about 2x for the size the panel draws him at

# Each layer and where it sits on the logo.
LAYERS = {"base": (0, 0), "brow": (186, 235), "teeth": (182, 284), "eyeL": (172, 204), "eyeR": (303, 204)}


def data_uri(name: str) -> tuple[str, int, int]:
    img = Image.open(os.path.join(RIG, name + ".png")).convert("RGBA")
    w, h = img.size
    small = img.resize((max(1, round(w * SCALE)), max(1, round(h * SCALE))), Image.LANCZOS)
    buf = io.BytesIO()
    small.save(buf, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode(), w, h


lines = [
    "// Generated by scripts/plugin-yeti.py from the yeti rig. Do not edit by hand.",
    "/** One layer of the yeti: where it sits on the 538x594 logo, its size there, and its pixels. */",
    "export type YetiLayer = { x: number; y: number; w: number; h: number; href: string }",
    "",
    "export const YETI: Record<'base' | 'brow' | 'teeth' | 'eyeL' | 'eyeR', YetiLayer> = {",
]
total = 0
for name, (x, y) in LAYERS.items():
    href, w, h = data_uri(name)
    total += len(href)
    lines.append(f"  {name}: {{ x: {x}, y: {y}, w: {w}, h: {h}, href: '{href}' }},")
lines.append("}")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {OUT}: {total} characters of image data")
